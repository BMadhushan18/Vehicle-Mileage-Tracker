// Generates seed/seed.sql: 2 vehicles, ~3 months of fill-ups, some no-ride days.
// Usage: node scripts/make-seed.mjs [email]   (default: dev@example.com)
// Dates end today, so "this month" always has data. Safe to run again: it replaces the sample vehicles.
import { mkdirSync, writeFileSync } from 'node:fs';

const email = (process.argv[2] || 'dev@example.com').toLowerCase();
if (!/^[^@\s']+@[^@\s']+$/.test(email)) {
  console.error('Please pass a valid email.');
  process.exit(1);
}

// Small deterministic random generator, so the output is the same each day.
let seed = 42;
const rand = () => (seed = (seed * 1664525 + 1013904223) % 4294967296) / 4294967296;
const pad = (n) => String(n).padStart(2, '0');
const iso = (d) => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
const today = new Date();
today.setHours(12, 0, 0, 0);
const start = new Date(today);
start.setDate(start.getDate() - 92);
const q = (s) => (s === null ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`);

const vehicles = [
  {
    id: 'seed-vehicle-pulsar',
    name: 'My Pulsar',
    type: 'bike',
    plate: 'BHK-4521',
    tank: 15,
    odo: 18250,
    color: '#3B82F6',
    kmPerDay: [25, 45],
    kmpl: [38, 46],
    fillEvery: [6, 9],
    price: 305,
    stations: ['Ceypetco Kandy Rd', 'IOC Kadawatha', 'Ceypetco Kiribathgoda'],
  },
  {
    id: 'seed-vehicle-dio',
    name: 'Dio Scooter',
    type: 'scooter',
    plate: 'BFC-1180',
    tank: 5.3,
    odo: 6420,
    color: '#22C55E',
    kmPerDay: [12, 22],
    kmpl: [44, 52],
    fillEvery: [7, 11],
    price: 305,
    stations: ['IOC Kadawatha', 'Ceypetco Ragama'],
  },
];

const lines = [
  '-- RideLog sample data. Generated by scripts/make-seed.mjs',
  `INSERT INTO users (id, email) VALUES ('seed-user-${email.replace(/[^a-z0-9]/g, '')}', ${q(email)}) ON CONFLICT(email) DO NOTHING;`,
];

for (const v of vehicles) {
  lines.push(`DELETE FROM fuel_entries WHERE vehicle_id = ${q(v.id)};`);
  lines.push(`DELETE FROM no_ride_days WHERE vehicle_id = ${q(v.id)};`);
  lines.push(`DELETE FROM vehicles WHERE id = ${q(v.id)};`);
  lines.push(
    `INSERT INTO vehicles (id, user_id, name, type, plate_number, fuel_type, tank_capacity_liters, start_odometer, color_tag) ` +
      `VALUES (${q(v.id)}, (SELECT id FROM users WHERE email = ${q(email)}), ${q(v.name)}, ${q(v.type)}, ${q(v.plate)}, 'petrol', ${v.tank}, ${v.odo}, ${q(v.color)});`,
  );

  // Pick no-ride days first: a few single days plus one 4-day trip.
  const noRide = new Set();
  const reasons = ['rain', 'sick', 'holiday', 'repair', 'other'];
  const noRideRows = [];
  const tripStart = 30 + Math.floor(rand() * 30);
  for (let i = 0; i < 4; i++) noRide.add(tripStart + i);
  for (let i = 0; i < 8; i++) noRide.add(1 + Math.floor(rand() * 90));

  let odo = v.odo;
  let nextFill = 0; // first fill on day 0 is the baseline
  let fillNo = 0;
  let priceNow = v.price;
  for (let day = 0; day <= 92; day++) {
    const date = new Date(start);
    date.setDate(start.getDate() + day);
    const dayIso = iso(date);
    const rode = !noRide.has(day);
    if (rode && day > 0) odo += v.kmPerDay[0] + rand() * (v.kmPerDay[1] - v.kmPerDay[0]);
    if (day === 45) priceNow = v.price - 12; // a price change in the middle

    if (day === nextFill && (rode || day === 0)) {
      const kmpl = v.kmpl[0] + rand() * (v.kmpl[1] - v.kmpl[0]);
      // Liters to refill = distance since last fill / km per liter (first fill: a full tank).
      const partial = fillNo > 0 && rand() < 0.15;
      let liters = fillNo === 0 ? v.tank * 0.9 : (odo - v._lastOdo) / kmpl;
      if (partial) liters = liters * 0.5;
      liters = Math.max(0.5, Math.min(v.tank, Math.round(liters * 100) / 100));
      const total = Math.round(liters * priceNow * 100) / 100;
      const id = `${v.id}-f${pad(fillNo)}`;
      lines.push(
        `INSERT INTO fuel_entries (id, vehicle_id, entry_date, odometer, liters, price_per_liter, total_cost, is_full_tank, station, note) ` +
          `VALUES (${q(id)}, ${q(v.id)}, ${q(dayIso)}, ${odo.toFixed(1)}, ${liters}, ${priceNow}, ${total}, ${partial ? 0 : 1}, ${q(v.stations[fillNo % v.stations.length])}, ${partial ? q('Only had cash for half') : 'NULL'});`,
      );
      if (!partial) v._lastOdo = odo;
      fillNo++;
      nextFill = day + v.fillEvery[0] + Math.floor(rand() * (v.fillEvery[1] - v.fillEvery[0] + 1));
    } else if (day === nextFill) {
      nextFill++; // didn't ride that day, fill tomorrow
    }

    if (!rode && day > 0) {
      noRideRows.push(
        `INSERT OR IGNORE INTO no_ride_days (id, vehicle_id, day, reason) VALUES (${q(`${v.id}-n${day}`)}, ${q(v.id)}, ${q(dayIso)}, ${
          day >= tripStart && day < tripStart + 4
            ? q('holiday')
            : q(reasons[Math.floor(rand() * reasons.length)])
        });`,
      );
    }
  }
  lines.push(...noRideRows);
}

mkdirSync(new URL('../seed/', import.meta.url), { recursive: true });
writeFileSync(new URL('../seed/seed.sql', import.meta.url), lines.join('\n') + '\n');
console.log(`Wrote seed/seed.sql for ${email}`);
